"""Locate the dataset: use the local CSV, else download IBM Telco, else make demo data."""
import logging
import urllib.request
from pathlib import Path

import pandas as pd

log = logging.getLogger(__name__)
IBM_URL = ("https://raw.githubusercontent.com/IBM/telco-customer-churn-on-icp4d/"
           "master/data/Telco-Customer-Churn.csv")


def ensure_dataset(path: Path) -> str:
    """Make sure `path` exists. Returns 'ibm-telco' or 'synthetic-sample'."""
    path = Path(path)
    marker = path.with_name("DATA_SOURCE.txt")
    if path.exists():
        if marker.exists() and "SYNTHETIC" in marker.read_text():
            return "synthetic-sample"
        return "ibm-telco"
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        log.info("Downloading IBM Telco churn dataset ...")
        urllib.request.urlretrieve(IBM_URL, path)
        pd.read_csv(path, nrows=5)  # sanity check it parses
        marker.write_text("IBM Telco Customer Churn dataset (public sample data).\n")
        return "ibm-telco"
    except Exception as exc:  # network or parse failure
        log.warning("Download failed (%s). Generating SYNTHETIC demo data instead.", exc)
        from data.generate_sample_data import generate
        generate().to_csv(path, index=False)
        marker.write_text("SYNTHETIC demo data - NOT real customers. Generated by generate_sample_data.py\n")
        return "synthetic-sample"


def load_raw(path: Path) -> pd.DataFrame:
    return pd.read_csv(path)
